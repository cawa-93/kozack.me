// Підказка старту гонки (§8.5, §11.3а): коли її показувати. Чисті розрахунки без Phaser (`tests/homedeparture.test.ts`); малює
// `RaceScene.drawStartHint`.

import type { Race } from "../sim/types";

/**
 * Чи показувати підказку старту (§8.5; [Змінено пізніше] рішенням автора 2026-11-03 — гонка стартує не з місця): гравець у цій
 * гонці ще нічого не натискав (`touched`), і або сцена показує гонку від самого старту (`fromStart`: від'їзд від дому чи свіжа
 * гонка — машина вже котиться зі `RACE.startSpeed`, а гравець ще не знає, як нею кермувати), або машина стоїть (гонка після
 * перезавантаження: поки машина котиться, підказки немає — гравець уже їхав, а спинилася — знову є). Раніше — лише «машина
 * стоїть»: гонка починалася з місця.
 */
export function startHintShown(race: Pick<Race, "speed">, fromStart: boolean, touched: boolean): boolean {
  return !touched && (fromStart || race.speed === 0);
}
