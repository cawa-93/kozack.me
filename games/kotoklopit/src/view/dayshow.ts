// Що з дня малювати цього кадру (§2.1 «Малювання й завантаження»): закрите непрозорою карткою гра не малює. Без Phaser.

/** Що закриває день цього кадру. */
export interface DayCover {
  /** На місці (§8.5 «На місці — кадр парковки»): під карткою пункту — кадр парковки сцени дороги, а не квартира. */
  away: boolean;
  /** Непрозора картка (`Overlay.covers`): титулка, кінець гри, титри, меню й вибір персонажа. */
  covered: boolean;
  /** Темрява дня 0–1 (засинання, аварія, виїзд із дому, після дороги): вона в шарі інтерфейсу сцени дня, над квартирою. */
  dark: number;
}

export interface DayShow {
  /** Чи малювати сцену дня взагалі. */
  scene: boolean;
  /** Чи малювати квартиру (і все, що над нею, під темрявою): інакше день не оновлює й не малює світу. */
  world: boolean;
}

export function dayShow({ away, covered, dark }: DayCover): DayShow {
  const scene = !away && !covered;
  return { scene, world: scene && dark < 1 };
}

/**
 * Скільки секунд згладжування дістає перший кадр квартири після того, як її не малювали (`WorldFrame.seconds`): більше за
 * найдовше згладжування вигляду (кроки, юрба, стілець, камера), тож квартира одразу на місці, а не доїжджає до нього на очах.
 */
export const REVEAL_SECONDS = 1;
