// Частини світу (крок 16, хвиля 0): квартира, котячий куточок, коти, персонаж і позначки. Кожна сама малює свій шматок
// світу зі стану гри, і кожну можна замінити окремо, не чіпаючи сцени: сцена лише кличе їх щокадру через `World`. Бабли,
// сердечка, індикатори сховищ, панель і сенсорні кнопки — не частини світу, їх веде сцена; частини лише кажуть, де на екрані
// що (`anchor`). Без Phaser.

import type { GameEvent } from "../../sim/events";
import type { Target } from "../../sim/targets";
import type { GameState } from "../../sim/types";
import type { RigFacing } from "../rig/types";

/** Точка світу на екрані, px до масштабу камери. */
export interface Point {
  x: number;
  y: number;
}

/** Де персонаж тримає кота: точка біля грудей і глибина, на якій кіт на руках лежить поверх нього (§9.12). */
export interface Hands extends Point {
  depth: number;
  /**
   * Новий вигляд (T2): куди персонаж дивиться на екрані цього кадру — за справою це не завжди напрям руху сима
   * (`personFacing`): за комп'ютером — спиною, купаючи кота — боком до душу. Кіт на руках і на колінах дивиться туди ж.
   * Немає — як `personFacing`.
   */
  facing?: Readonly<RigFacing>;
  /**
   * Новий вигляд (T2): персонаж саме бере кота на руки чи опускає (`pickUp`, `putDown`) — кіт рухається з кистями, а не
   * стрибає в гніздо чи з нього. null чи немає — ні.
   */
  lift?: HandsLift | null;
}

/**
 * Кіт, якого персонаж бере на руки чи опускає (контракт N4a: `personCatLift`, `personCatGrip`). Частина котів малює його в
 * точці lerp(місце на підлозі, руки, `w`), де місце на підлозі — lerp(там, де кіт стоїть сам, під кистями, `grip`): гніздо
 * `pet` кота (спинка) — у точці `at`.
 */
export interface HandsLift {
  /** Який кіт: його малюють біля рук і тоді, коли сим уже відпустив його (опускає). */
  cat: number;
  /** Наскільки кіт у руках: 0 — стоїть на підлозі, 1 — у гнізді рук (`personCatLift`). */
  w: number;
  /** Наскільки місце кота на підлозі — під кистями, а не там, де він стоїть сам: 0…1. */
  grip: number;
  /** Де кисті підхоплюють кота на підлозі, px світу (`personCatGrip`). */
  at: Point;
}

/** Точки кота, яких торкається персонаж: над головою (бабли, пір'їнка вудочки) і спинка (рука, що гладить). */
export interface CatPoints {
  head: Point;
  back: Point;
  /**
   * Рот (звідки хропіння, задишка й чхання — `iso/fx.ts`), ракурс, масштаб кота й чи видно сам скелет (а не лише очі з-під
   * меблів).
   */
  mouth?: Point;
  /**
   * Корінь скелета на екрані (точка підлоги під котом, піднята на висоту меблів; у юрбі — там, де кота намальовано): до нього
   * обертається персонаж, що гладить кота чи грається з ним (`touchFacing`).
   */
  root?: Point;
  facing?: Readonly<RigFacing>;
  scale?: number;
  rigShown?: boolean;
}

/** Що кадр каже частинам світу, крім стану гри. */
export interface WorldFrame {
  /** Час сцени, мс: від нього йдуть усі анімації. */
  time: number;
  /** Скільки секунд пройшло за кадр (0, коли гра стоїть). */
  seconds: number;
  /** Персонаж іде: підстрибує на кроках (§8.4). */
  moving: boolean;
  /** Засинання 0–1 (§8.8): очі заплющуються, голова хилиться. */
  sleepiness: number;
  /** Гра стоїть (картка, пауза, кінець гри, засинання, «поверніть телефон»): ціль дії не підсвічується. */
  blocked: boolean;
  /** Режим розробки: приховані числа над котами (§11.5). */
  showHidden: boolean;
  /**
   * Хвилина для світла доби (§8.9, `light/daylight.ts`): зазвичай `state.minute`; режим розробки підміняє її (`?light=`,
   * `Session.lightAt`), а `null` — світло доби вимкнене зовсім (звірка знімків: удень світло не додає жодного пікселя).
   */
  lightMinute: number | null;
}

export interface WorldPart {
  /**
   * Перший прохід кадру: намалювати свій шматок світу зі стану. Частини оновлюються по черзі (див. `World`): персонаж,
   * коти, куточок, квартира, позначки, — тож усе, що частина питає в інших (`WorldQuery`), уже цього кадру.
   */
  update(state: GameState, frame: WorldFrame): void;
  /**
   * Другий прохід, коли всі частини вже оновилися: те, що залежить від частини, оновленої пізніше (рука персонажа на
   * спинці кота, якого щойно намальовано). Необов'язково.
   */
  lateUpdate?(state: GameState, frame: WorldFrame): void;
  /** Подія гри (§11.4) — у мить, коли вона сталася: разові анімації, червона смужка відмови. `time` — час сцени, мс. */
  onEvent?(event: GameEvent, time: number): void;
  /** День показують заново (нова гра, перегравання, сценарій): забути намальованих котів тощо. */
  reset(): void;
  /** Сцена закривається: прибрати все своє. */
  destroy(): void;
  /**
   * Де на екрані бабл і підсвітка для `id`, якщо він цієї частини й його зараз видно: точка над ним; інакше null.
   * Кличуть і поза кадром (бабл події летить за котом), тож частина відповідає з поточного стану.
   */
  anchor(id: string): Point | null;
  /**
   * Підсвітити ціль дії (§8.2), якщо вона цієї частини: true — підсвітила. `alpha` — яскравість пульсу 0–1, однакова
   * для всіх частин. Кличе частина позначок щокадру, поки є ціль.
   */
  highlight(target: Target, alpha: number): boolean;
}

/** Квартира: стіни, меблі, сховища та їх наповнення, речі на поверхнях, дрібнички, ящики. */
export interface ApartmentPart extends WorldPart {
  /** Точка над річчю квартири, навіть коли її зараз немає: запаси летять із ящиків, що щойно спорожніли (§6.4). */
  objectAnchor(id: string): Point | null;
}

/** Персонаж: його голова й руки потрібні котам і баблам, щітка пилососа — підлозі (туди втягується прибране). */
export interface PersonPart extends WorldPart {
  /** Над головою: тут бабли персонажа (камера йде не за цією точкою, а за ногами за симуляцією — `followTarget`, §8.4). */
  readonly head: Point;
  /** Де персонаж тримає кота (§9.12). */
  readonly hands: Hands;
  /** Щітка пилососа в руках на екрані (§8.7, «Пилосос у руках»), px світу; null — пилососа в руках немає чи його не видно. */
  readonly brush: Point | null;
}

/** Коти. */
export interface CatsPart extends WorldPart {
  /** Точки кота, якого частина зараз малює (навіть схованого), чи null, якщо такого немає. */
  points(cat: number): CatPoints | null;
}

/** П'ять частин світу. */
export interface WorldParts {
  apartment: ApartmentPart;
  /** Котячий куточок на підлозі: миски, лотки, техніка, безлад. */
  floor: WorldPart;
  cats: CatsPart;
  person: PersonPart;
  /** Позначки: підсвітка цілі, смуги прогресу, екран комп'ютера, пошук роботи. */
  marks: WorldPart;
}

/** Що частини питають в усього світу: точки персонажа й котів, якорі інших частин. */
export interface WorldQuery {
  /** Якір за id: `person`, `cat:N`, `item:N`, `mess:N` чи id речі квартири — до частини-власниці. */
  anchor(id: string): Point | null;
  /** Точка над річчю квартири, навіть коли її зараз немає. */
  objectAnchor(id: string): Point | null;
  /** Підсвітити ціль у частині, якій вона належить. */
  highlight(target: Target, alpha: number): boolean;
  readonly person: { readonly head: Point; readonly hands: Hands; readonly brush: Point | null };
  cat(id: number): CatPoints | null;
}
