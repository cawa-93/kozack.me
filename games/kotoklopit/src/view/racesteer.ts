// Перестроювання в гонці (§8.5, §10): що гравець попросив цього кадру — клавішею чи джойстиком. Без Phaser.

export type LaneDir = -1 | 0 | 1;

export class LaneSteer {
  private next: LaneDir = 0;

  /**
   * Клавіша ←/A чи →/D: нове натискання — одне перестроювання; автоповтор затиснутої (`event.repeat`) — ні, як одне відхилення
   * джойстика й клавіші дня.
   */
  key(dir: -1 | 1, repeat: boolean): void {
    if (!repeat) this.next = dir;
  }

  /** Джойстик відхилили вбік: одне відхилення — одне перестроювання (наступне — після повернення до середини, це стежить сцена). */
  push(dir: -1 | 1): void {
    this.next = dir;
  }

  /** Перестроювання цього кадру; далі — жодного, доки не попросять знову. */
  take(): LaneDir {
    const dir = this.next;
    this.next = 0;
    return dir;
  }

  /** Забути, що попросили: керування нової гонки не переходить із минулої. */
  clear(): void {
    this.next = 0;
  }
}
