// Страву поставили на стіл і кнопку тримають далі (§8.7, §10): це ще одне натискання — персонаж сідає їсти. Без Phaser: сцена
// лише пам'ятає, коли страву поставили.

/** Скільки мс кнопку тримають після того, як поставили страву: довше за коротке натискання, яке страву лише ставить. */
export const MEAL_HOLD_MS = 300;

/**
 * Що робити сцені цього кадру: `servedAt` — коли натискання поставило страву на стіл (мс сцени; null — не ставило), `hold` — чи
 * кнопку ще тримають. `wait` — тримають, але ще недовго; `sit` — натиснути дію ще раз; `idle` — нічого (і забути `servedAt`).
 */
export function mealHold(servedAt: number | null, now: number, hold: boolean): "idle" | "wait" | "sit" {
  if (servedAt === null || !hold) return "idle";
  return now - servedAt >= MEAL_HOLD_MS ? "sit" : "wait";
}
