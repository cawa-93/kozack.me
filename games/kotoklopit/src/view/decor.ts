/** Площина задньої стіни: `y` — лице стіни ряду y = 0 (y = 1), `x` — лице стовпця x = 0 (x = 1). */
export type WallFace = "y" | "x";

/** Точка видимого скла вікна в площині скла: [уздовж стіни (як `Pane.span`), висота z]. */
export type GlassPoint = readonly [number, number];

/** На стільки клітинок рама й скло вікон — у глибині стіни від її лиця (видно укоси; `art/env/window/*.svg`). */
export const GLASS_RECESS = 0.1;

/**
 * Вікно (`env/window/<room>`): клітинка стіни, лице, отвір уздовж стіни (`span`, координата x для лиця `y`, y для лиця `x`) і
 * по висоті (`z`). `sill` — підвіконня з `WINDOWS` (там сидять коти); у кухонного вікна його немає — воно лише декор.
 * `glass` — видиме скло стулок (§8.9: темніє й теплішає лише воно): многокутники в площині скла (`GLASS_RECESS` від лиця
 * стіни), без рами, укосів, ручок, фіранок і штори — за малюнком вікна (перевіряє `tests/windowglass.test.ts`).
 */
export interface Pane {
  room: RoomId;
  wall: Vec;
  face: WallFace;
  span: readonly [number, number];
  z: readonly [number, number];
  sill?: string;
  glass: readonly (readonly GlassPoint[])[];
}

/** Многокутник скла в долях клітинки стіни (0–1 уздовж стіни) → уздовж стіни від `along`. */
const glassAt = (along: number, polys: readonly (readonly GlassPoint[])[]): readonly (readonly GlassPoint[])[] =>
  polys.map((poly) => poly.map(([u, z]): GlassPoint => [along + u, z]));

