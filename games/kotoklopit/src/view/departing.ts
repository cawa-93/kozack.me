// Виїзд із дому (§8.5 «Виїзд із дому — від'їзд від свого будинку», рішення автора 2026-11-03): поїздки, що щойно вирушили від
// дверей (вибір пункту в «Куди поїхати?», `startTrip`), — для них день не запускає гонку одразу, а спершу темніє, і сцена дороги
// показує від'їзд від свого будинку (`RaceScene`, режим «depart»). Лише в пам'яті сторінки, не в збереженні: перезавантаження
// посеред від'їзду чи гонки — одразу гонка, як і раніше; знайда в притулок і інші входи в дорогу сюди не потрапляють. Позначає
// поїздку той, хто її почав (день; сценарій режиму розробки з `leave`), а забирає день, коли починає від'їзд.

import type { Trip } from "../sim/types";

const departing = new WeakSet<Trip>();

/** Поїздка щойно вирушила від дверей: день покаже від'їзд від свого будинку. */
export function markDeparture(trip: Trip): void {
  departing.add(trip);
}

/** Чи поїздка щойно вирушила від дверей; позначку забрано — від'їзд показують раз. */
export function takeDeparture(trip: Trip): boolean {
  const marked = departing.has(trip);
  departing.delete(trip);
  return marked;
}
