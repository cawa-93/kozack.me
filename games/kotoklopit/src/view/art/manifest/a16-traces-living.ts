// Маніфест котячих слідів вітальні (§9.12, «Котячі сліди в квартирі»; §8.3): гра починається в цілій квартирі, а сліди
// з'являються з котами й лишаються (`home.traces`, `CatTrace` у `src/sim/types.ts`). Кожен слід — накладка
// `env/trace/<слід>` поверх кадру-господаря, на якому він лежить: те саме полотно, той самий pivot і та сама `res`, тож вигляд
// ставить її в ту саму точку, що й господаря, трохи над ним. Атлас обрізає прозорі краї кадру, тож велике полотно господаря
// атлас не роздуває. Господарі без накладки — цілі: шпалери, килим, стіна й оббивка під слідом домальовані.
// SVG — `art/env/trace/<слід>.svg` (`art/STYLE.md`).
//
// Геометрія — з записів господарів (`a01-build.ts`, `a04-rooms.ts`), а не копією чисел: зміниться полотно господаря — за ним
// піде й накладка.

import type { ArtEntry, ArtId } from "../types";
import { MANIFEST as BUILD } from "./a01-build";
import { MANIFEST as ROOMS } from "./a04-rooms";

/** Полотно, pivot і `res` господаря: накладка сліду лягає на нього точно. */
function over(host: ArtId): Pick<ArtEntry, "size" | "pivot" | "res"> {
  const entry = [...BUILD, ...ROOMS].find((e) => e.id === host);
  if (!entry) throw new Error(`Немає господаря «${host}» для котячого сліду`);
  return { size: entry.size, pivot: entry.pivot, ...(entry.res === undefined ? {} : { res: entry.res }) };
}

