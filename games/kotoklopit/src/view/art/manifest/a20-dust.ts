/** Стан `mess/cobweb`: які стіни в куті високі (задні, 200). */
export type CobwebState = "corner" | "wall-x" | "wall-y";

/**
 * Стан павутини в куті з точкою підлоги `corner` (клітинки, верхня вершина ромба клітинки кута — `(room.x, room.y)`):
 * `corner` — обидві стіни біля кута задні (ліворуч стовпець x = 0, угорі ряд y = 0), `wall-x` — задня лише стіна вгорі
 * (y = const, на екрані йде праворуч-униз від кута), `wall-y` — лише ліворуч (x = const, ліворуч-униз). Задньої стіни
 * біля кута немає — null: павутині там не бути (внутрішні стіни низькі, 66).
 */
export function cobwebState(corner: Vec): CobwebState | null {
  const x = Math.floor(corner.x);
  const y = Math.floor(corner.y);
  const left = wallKind(x - 1, y) === "back";
  const above = wallKind(x, y - 1) === "back";
  if (left && above) return "corner";
  if (above) return "wall-x";
  if (left) return "wall-y";
  return null;
}

