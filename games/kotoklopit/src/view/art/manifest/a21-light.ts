function shelf(id: keyof typeof SHELF): ArtEntry {
  const { size, pivot, flameX } = SHELF[id];
  return { id, size, pivot, points: { flame: { x: flameX, y: pivot.y - LIGHT_ART.shelf[id].flame } }, states: ["out", "lit"] };
}

