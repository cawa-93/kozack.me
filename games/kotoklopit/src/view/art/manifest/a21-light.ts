import type { Vec } from "../../../sim/types";
import type { ArtEntry, ArtPoint, ArtSize } from "../types";
import { iso } from "./lib/geometry";

/** Округлення до 0,5 одиниці, як точки решти маніфесту. */
const half = (v: number): number => Math.round(v * 2) / 2;
/** Точка кадру: pivot + точка (клітинки від pivot) на висоті `z`. */
const pointAt = (pivot: ArtPoint, p: Vec, z: number): ArtPoint => {
  const o = iso(p, z);
  return { x: half(pivot.x + o.x), y: half(pivot.y + o.y) };
};

