const SCONCE = {
  "env/sconce/back": { size: { w: 48, h: 142 }, pivot: { x: 36, y: 138 } },
  "env/sconce/left": { size: { w: 48, h: 160 }, pivot: { x: 12, y: 156 } },
} as const satisfies Record<keyof typeof LIGHT_ART.sconce, { size: ArtSize; pivot: ArtPoint }>;

function sconce(id: keyof typeof SCONCE): ArtEntry {
  const { size, pivot } = SCONCE[id];
  const art = LIGHT_ART.sconce[id];
  const axis = art.face === "y" ? { x: 0, y: art.out } : { x: art.out, y: 0 };
  return { id, size, pivot, points: { lamp: pointAt(pivot, axis, art.lamp) }, states: ["off", "on"] };
}

