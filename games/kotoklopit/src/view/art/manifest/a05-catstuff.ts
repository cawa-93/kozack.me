// Маніфест пакета A5 «Котячі речі» (крок 16, GRAPHICS_PLAN.md, «Хвиля 2»): миски й поїлки, фонтанчик, лотки, будиночки,
// кігтеточки, автогодівниці, робот і док, переноска, замок, вудочки; речі в руках — сира порція, тарілки, судочок, совок
// корму.
//
// Речі котячого кутка (`HomeItem`, §9.12) і техніка (`ThingKind`, §6.4) — `item/<вид>/<якість>[/<стан>]`: `cheap` і
// `premium` — два варіанти з магазину (`VARIANT_TITLES` у `src/ui/titles.ts`). Pivot — точка підлоги під центром речі
// (центр місця `slotCenter`, у іграшки — де вона лежить). Висоти — відносно дорослого кота ≈ 56.
//
// Стани з кормом: `<корм>-<рівень>`, де корм — `cheap` («Щодня»), `premium` («Гурман») чи `sterile` (для стерилізованих,
// зеленуватий, §9.8), рівень — скільки порцій (`BOWL_CAPACITY` 2) чи `low` / `full` у годівниці.

import type { ArtEntry } from "../types";
import { floorItem } from "./lib/geometry";

const QUALITIES = ["cheap", "premium"] as const;
/** Корм у мисці: порожньо, далі вид корму × порції (1 — до порції, 2 — повна). */
const BOWL_FOOD = ["empty", "cheap-1", "cheap-2", "premium-1", "premium-2", "sterile-1", "sterile-2"] as const;
/** Корм у бункері годівниці. */
const FEEDER_FOOD = ["empty", "cheap-low", "cheap-full", "premium-low", "premium-full", "sterile-low", "sterile-full"] as const;
/** Наповнювач у лотку (`LitterItem.litter`): немає; глиняний (`cheap`) чи силікагелевий (`premium`) — чистий, з грудками, брудний. */
const LITTER_FILL = ["empty", "cheap", "cheap-used", "cheap-dirty", "premium", "premium-used", "premium-dirty"] as const;

/** Записи обох якостей: `make(якість)` дає решту запису. */
const both = (kind: string, make: (q: (typeof QUALITIES)[number]) => Omit<ArtEntry, "id">): ArtEntry[] =>
  QUALITIES.map((q): ArtEntry => ({ id: `item/${kind}/${q}`, ...make(q) }));

export const MANIFEST: readonly ArtEntry[] = [
  // Миска для корму (§9.12): пластикова (`cheap`) і керамічна з золотим обідком (`premium`). Корм меншає поступово — видно,
  // хто ковтає за мить, а хто клює по зернятку; кіт їсть, сидячи за мискою.
  ...both("bowl", () => ({ ...floorItem(48, 32, 10), states: BOWL_FOOD })),
  // Миска для води (§9.12): пластикова й керамічна поїлка; рівень води (`WATER_CAPACITY` ковтків): порожня, мало, половина,
  // повна. Перекинута «Фонтанолюбом» — `mess/puddle`.
  ...both("water", () => ({ ...floorItem(48, 32, 10), states: ["empty", "low", "half", "full"] })),
  // Лоток (§9.12): простий відкритий (`cheap`) і закритий із дашком над задньою половиною (`premium`, вхід спереду).
  // Наповнювач — `LITTER_FILL`; брудний (`isDirty`) — грудки й запах (хвилі запаху — `fx/smell`). Кіт присідає в ньому.
  ...both("litter", (q) => ({ ...floorItem(88, q === "premium" ? 84 : 56, 20), states: LITTER_FILL })),
  // Іграшка-вудочка (§9.12): паличка з мотузкою й пір'ям; дешева — зелене пір'я, дорога — яскраве й «інтерактивне». Стани:
  // `floor` — лежить на підлозі (pivot — точка під її серединою), `hidden` — загнана під диван чи холодильник, видно лише
  // пір'їнку (`ToyItem.hidden`), `teeth` — у зубах кота (pivot — де кіт її тримає, гніздо `teeth`), `hand` — у руці
  // персонажа під час гри (pivot — де рука тримає паличку, гніздо `rod`; мотузка з пір'ям звисає).
  ...both("toy", () => ({
    size: { w: 128, h: 128 },
    pivot: { x: 64, y: 72 },
    points: { feather: { x: 104, y: 100 } },
    states: ["floor", "hidden", "teeth", "hand"],
  })),
  // Будиночок для сну й схованки (§9.12): картонний з дахом і круглим входом (`cheap`) і м'який затишний (`premium`). Кіт
  // усередині — лише очі в темному вході (`door`).
  ...both("house", () => ({ ...floorItem(96, 120, 22), points: { door: { x: 48, y: 82 } } })),
  // Кігтеточка (§9.12): картонна (`cheap`, низька) і сизалева на підставці з поличкою й помпоном (`premium`). Кіт дере її
  // стоячи на задніх лапах.
  ...both("scratcher", (q) => ({ ...floorItem(76, q === "premium" ? 124 : 96, 16) })),
  // Автогодівниця над місцем миски (§9.12, правка автора 2026-10-23): проста — вузький сірий бункер (`cheap`), розумна —
  // ширший світлий із вогником (`premium`: зелений, коли корм є, жовтий — бункер порожній). У віконці видно корм
  // (`FEEDER_FOOD`); стоїть позаду миски на тій самій клітинці.
  ...both("feeder", (q) => ({ ...floorItem(q === "premium" ? 56 : 48, 76, 12), states: FEEDER_FOOD })),
  // Фонтанчик для води (§8.7): білий купол зі струменем, що дугою падає у воду, — накладка на кожну миску з водою (той
  // самий pivot, що в `item/water/*`); простий (`cheap`) і тихий (`premium`).
  ...both("fountain", () => ({ ...floorItem(48, 48, 10) })),
  // Робот-пилосос (§8.7): простий сірий (`cheap`) і розумний темний (`premium`) диск; `charging` — на доку, синій вогник,
  // `cleaning` — їде (`ROBOT_ROUTE`), зелений вогник. На ньому може їхати кіт (`top`).
  ...both("robot", () => ({ ...floorItem(64, 40, 12), points: { top: { x: 32, y: 18 } }, states: ["charging", "cleaning"] })),
  // Переноска (§8.5, §9.12 «Переноска»): пластикова сіра (`cheap`) і надійна вишнева (`premium`), стоїть відчинена біля
  // дверей (`CARRIER_SPOT`). `body` — сама переноска з відчиненими дверцятами; `grate` — лише дверцята з ґратками, що
  // кладуться поверх кота, який спить усередині (`inside`): крізь них видно клубочок шерсті.
  ...both("carrier", () => ({ ...floorItem(96, 96, 18), points: { inside: { x: 48, y: 66 } }, states: ["body", "grate"] })),
  // Замок на шафку з кормом (§9.12, «Кмітливість у бешкеті»): дитячий замочок (`cheap`, «Зломник» інколи відчиняє) і
  // магнітний (`premium`); висить на дверцятах `env/cat-cabinet` (точки `lock` / `lock-open`), pivot — центр корпусу.
  ...both("lock", () => ({ size: { w: 20, h: 26 }, pivot: { x: 10, y: 15 } })),
  // Док робота-пилососа (§8.7) біля `ROBOT_DOCK` (17,6; 8,2): низька темна база з контактами; спільна для обох роботів.
  { id: "item/robot-dock", ...floorItem(64, 40, 14) },

  // --- Речі в руках (`Item`, §8.4: у руках лише одна): тримає гніздо `held` скелета персонажа (pivot — низ речі
  // посередині, на долонях); ті самі кадри лежать на столі й стільницях (точки `dish` речей кухні). Плиту показує сама
  // плита (`env/stove`). `cheap` / `premium` — якість продуктів (§6.4: «Звичайні» і «Фермерські»); дорогу видно з
  // золотої цятки.

  // Сира порція (§8.7): паперовий пакунок із зеленню — з холодильника на плиту.
  { id: "item/dish/raw", ...floorItem(40, 40, 6), states: QUALITIES },
  // Готова страва (§8.7): тарілка з помаранчевою їжею.
  { id: "item/dish/meal", ...floorItem(44, 32, 8), states: QUALITIES },
  // Пригоріла страва (§8.7): тарілка з чорним, курить (дим — `fx/smoke`); її викидають у смітник.
  { id: "item/dish/burnt", ...floorItem(44, 32, 8), states: QUALITIES },
  // Мамин судочок (§6.4, рішення автора 2026-10-26): прозорий контейнер із синьою кришкою й сердечком — готова страва з
  // холодильника.
  { id: "item/dish/mom", ...floorItem(40, 36, 6) },
  // Совок котячого корму (§9.12): металевий совочок із гранулами — «Щодня» (`cheap`), «Гурман» (`premium`) чи для
  // стерилізованих (`sterile`, зеленуватий, §9.8). Несуть від шафки чи бака до миски.
  { id: "item/scoop", ...floorItem(40, 28, 6), states: ["cheap", "premium", "sterile"] },
];
