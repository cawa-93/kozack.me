/**
 * Вікно — еталон F1a `env/window/bedroom`: рама з укосами, склом, кватиркою й фіранками на лицьовій грані стіни y = 0, без
 * решти блоку стіни (її малює плита кімнати); pivot — верхня вершина ромба клітинки стіни. Вікно в стіні x = 0 —
 * дзеркальне (лицьова грань — праворуч від тієї самої вершини): полотно те саме, pivot віддзеркалено.
 */
const WINDOW: Geometry = { size: { w: 128, h: 204 }, pivot: { x: 100, y: 178 } };

/** Вікно над підвіконням `sill` (`WINDOWS[].wall` — клітинка стіни). */
function windowOver(sill: string): ArtEntry {
  const w = WINDOWS.find((v) => v.sill === sill);
  if (!w) throw new Error(`Немає вікна над «${sill}»`);
  const pivot = w.wall.y === 0 ? WINDOW.pivot : { x: WINDOW.size.w - WINDOW.pivot.x, y: WINDOW.pivot.y };
  return { id: `env/window/${roomAt(objectById(sill)) ?? "living"}`, size: WINDOW.size, pivot };
}

/**
 * Підвіконня: верх дошки на висоті 70; `seat` — де сидить кіт: посередині дошки на 0,12 від стіни з вікном, в обох
 * кімнатах однаково (ізометричне дзеркало; так його садовить `isoCatPerch` у `world/objects.ts`). У симуляції
 * (`WINDOWS[].seat`) кіт у вітальні сидить на 0,3 від стіни — на самому краї дошки 0,28 завглибшки.
 */
const SILL_TOP = 70;
const SILL_SEAT = 0.12;
function sill(id: string): ArtEntry {
  const object = objectById(id);
  const geometry = box(object, { top: SILL_TOP, tall: SILL_TOP + 6 });
  const wall = WINDOWS.find((v) => v.sill === id)?.wall;
  // Стіна з вікном — ряд y = 0 (дошка вздовж x) чи стовпець x = 0 (дошка вздовж y).
  const seat = wall?.y === 0 ? { x: object.x + object.w / 2, y: object.y + SILL_SEAT } : { x: object.x + SILL_SEAT, y: object.y + object.h / 2 };
  const { fx, fy } = fractionIn(object, seat);
  return { id: `env/${id}`, ...geometry, points: { seat: pointsOn(object, geometry)(fx, fy, SILL_TOP) } };
}

/**
 * Сегмент внутрішньої стіни чи переднього плінтуса (пакет A1b, `art/env/wall/<вид>/<сегмент>.svg`): полотно `slab` його
 * клітинок, ширше на `WALL_MARGIN` з кожного боку — важкий низ (8,5) на кутах сліду з полем `PAD` 8 стояв би за 3,75 від
 * краю, а треба щонайменше 4 (`tests/art.test.ts`); грань і кришка ще й заходять на 0,03 клітинки під сусідній сегмент,
 * що лягає пізніше. Pivot — та сама верхня вершина першої клітинки.
 */
const WALL_MARGIN = 2;
function wallSegment(s: (typeof WALL_SEGMENTS)[number]): ArtEntry {
  const { size, pivot } = slab(rectCells(s.rect), s.rect, s.kind === "inner" ? WALL_HEIGHT.inner : WALL_HEIGHT.front);
  return { id: s.id, size: { w: size.w + 2 * WALL_MARGIN, h: size.h + 2 * WALL_MARGIN }, pivot: { x: pivot.x + WALL_MARGIN, y: pivot.y + WALL_MARGIN } };
}

