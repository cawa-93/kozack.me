// Маніфест пакета «Котячі сліди: шафка, двері, коробки» (рішення автора 2026-11-02, §9.12, «Котячі сліди в квартирі»): сліди
// котів, які раніше були намальовані просто на меблях, тепер — окремі накладки `env/trace/<слід>` (`CatTrace`), тож на старті
// квартира ціла, а слід з'являється, коли кіт уперше це зробив.
//
// Накладка має ті самі полотно, pivot і роздільність, що її «господар» (кадр, на якому слід лежить): вигляд ставить її в ту
// саму точку трохи над господарем. Якщо господар має стани, накладка має ті самі (вигляд показує той самий стан); стан, у
// якому сліду не видно, — порожній кадр (конвеєр робить з нього один прозорий піксель). Слід, що лежить на кількох кадрах,
// — кілька записів: `env/trace/<слід>` і `env/trace/<слід>/<частина>` (SVG `art/env/trace/<слід>/<частина>.svg`).
//
// Геометрію беремо з записів господарів (модулі пакетів A2 і A4), а не дублюємо числа: так полотно й pivot збігаються точно.

import type { ArtEntry, ArtId } from "../types";
import { MANIFEST as KITCHEN } from "./a02-kitchen";

/** Накладка-слід `id` на кадрі господаря `host` з модуля `entries`: його полотно, pivot, роздільність і стани. */
function traceOn(id: ArtId, entries: readonly ArtEntry[], host: ArtId): ArtEntry {
  const entry = entries.find((e) => e.id === host);
  if (!entry) throw new Error(`Слід «${id}»: немає господаря «${host}»`);
  return {
    id,
    size: entry.size,
    pivot: entry.pivot,
    ...(entry.res === undefined ? {} : { res: entry.res }),
    ...(entry.states === undefined ? {} : { states: entry.states }),
  };
}

export const MANIFEST: readonly ArtEntry[] = [
  // Подряпини кігтями на лівих дверцятах шафки з кормом (`cabinet`: кіт лапав дверцята, «Кмітливість у бешкеті»). Стани —
  // шафки: `closed` — три борозни знизу біля стику; `open` — порожньо (ліві дверцята розчахнуті внутрішнім боком до кімнати).
  traceOn("env/trace/cabinet", KITCHEN, "env/cat-cabinet"),
];
