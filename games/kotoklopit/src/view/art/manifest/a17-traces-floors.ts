// Маніфест котячих слідів на підлогах спальні, ванної й кухні (GAME_DESIGN §9.12, «Котячі сліди в квартирі»; пакет
// «Підлоги спальні, ванної й кухні»). Квартира на старті ціла: слід — окрема накладка `env/trace/<слід>` (SVG
// `art/env/trace/<слід>.svg`), а плита підлоги під нею — без сліду. Усі три сліди цього пакета — від «котоднів»
// (`home.catDays`), своєї дії кота не мають; який слід уже з'явився — `home.traces` (`CatTrace`).
//
// Накладка має те саме полотно, pivot і роздільність, що й її господар — плита підлоги з пакета «Будова» (`a01-build.ts`):
// квартира ставить її в ту саму точку toScreen(room.x, room.y), трохи над плитою й під усім, що стоїть на підлозі. Разом із
// плитою — той самий слід, що до котячих слідів був намальований у самій плиті. Геометрію беремо із запису господаря, тож
// вона збігається точно й міняється разом із ним. Станів у плит немає — немає їх і в накладок. Атлас обрізає прозорі краї
// кадру, тож велике полотно на атлас не важить.

import type { CatTrace } from "../../../sim/types";
import type { ArtEntry, ArtId } from "../types";
import { MANIFEST as BUILD } from "./a01-build";

/** Накладка сліду `trace` на кадр-господаря `host` (запис пакета «Будова»): те саме полотно, pivot і res. */
function onHost(trace: CatTrace, host: ArtId): ArtEntry {
  const entry = BUILD.find((e) => e.id === host);
  if (!entry) throw new Error(`Немає господаря «${host}» для сліду «${trace}»`);
  const { size, pivot, res } = entry;
  return { id: `env/trace/${trace}`, size, pivot, ...(res !== undefined && { res }) };
}

export const MANIFEST: readonly ArtEntry[] = [
  // Ванна: ближній куточок смугастого килимка перед душем (≈ 8,9; 2,57) загнуто вгору виворотом, під ним видно плитку.
  onHost("bath-mat", "env/room/bathroom/floor"),
  // Спальня: петля, що вибилася з краю круглого плетеного килимка біля ліжка (≈ 3,0; 2,1) — кіт зачепив кігтями.
  onHost("bedroom-rug", "env/room/bedroom/floor"),
  // Кухня: надірваний і загнутий клапоть лінолеуму між плитою й столом (≈ 16,2; 2,5) — дірка до основи й клапоть виворотом.
  onHost("lino", "env/room/kitchen/floor"),
];
