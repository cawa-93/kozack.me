/** Точка рамки парковки → точка полотна `race/lot`: pivot полотна стоїть у `entrance`. */
function lotPoint(p: { readonly x: number; readonly y: number }): { x: number; y: number } {
  return { x: p.x - RACE_LOT.entrance.x + RACE_LOT.pivot.x, y: p.y - RACE_LOT.entrance.y + RACE_LOT.pivot.y };
}

