// Маніфест пакета A13 «Оформлення UI» (крок 16, GRAPHICS_PLAN.md, «Хвиля 2»): папір і чорнильні рамки карток, кнопки,
// вкладки телефону, повзунки редактора, чипи рис, поле імені, фінальна смуга часу, хрестик картки, екран «поверніть
// телефон» (`src/ui/overlay.css`, `index.html`); у Phaser — панель HUD, кнопка телефону й повного екрана, сенсорні кнопки
// (`src/view/hud.ts`, `src/view/touch.ts`).
//
// DOM бере картинки не з атласу, а прямо з SVG (`url()` в `overlay.css`; Vite видає файл з хешем, чітко на будь-якій
// щільності екрана). Тому DOM-запис зі станами розбито на окремі id на стан (`ui/button/normal`, `ui/button/primary`…):
// кожен стан — свій SVG, на який посилається CSS. Кадри цих записів в атласі бачить лише галерея, тож `res` 1 — щоб не
// займати сторінки. Одиниці DOM-записів — CSS-пікселі: 1 одиниця = 1 px. Рамки, кнопки й смуги — «дев'ять частин» (CSS
// `border-image`): кути не тягнуться, `points.slice` — відступ кутів від краю (зріз `border-image-slice`); поле полотна
// 4,6 одиниці (`art/STYLE.md` §2) CSS виносить за межі елемента через `border-image-outset: 4px`. Кольори тла, тексту й
// тіні карток — CSS тими самими токенами `art/palette.ts`; рукописний шрифт заголовків (Pangolin, OFL) — файли в
// `src/ui/fonts/`, а не кадри, тож у маніфесті його немає.
//
// Записи HUD і сенсорного керування — кадри атласу (їх бере T3: `hud.ts`, `touch.ts`), у пікселях полотна гри 1280 × 720
// (`BASE_WIDTH`), `res` за замовчуванням; стани — класи `st-*` в одному SVG. Малюються непрозорими: напівпрозорість
// кнопок і смуги (зараз 0,12–0,92) задає код.

import type { ArtEntry } from "../types";
import { centered } from "./lib/geometry";

/** Відступ дев'яти частин: однаковий з усіх боків. */
const slice = (s: number): Pick<ArtEntry, "points"> => ({ points: { slice: { x: s, y: s } } });

/** Запис DOM: полотно з pivot у центрі, `res` 1 (кадр в атласі — лише для галереї), необов'язковий відступ дев'яти частин. */
const dom = (w: number, h: number, s?: number): Omit<ArtEntry, "id"> => ({ ...centered(w, h), res: 1, ...(s !== undefined ? slice(s) : {}) });

