/** Колір за каналами, 0–1. */
export interface Rgb {
  readonly r: number;
  readonly g: number;
  readonly b: number;
}

/** 0xrrggbb → `Rgb`. */
export function rgb(hex: number): Rgb {
  return { r: ((hex >> 16) & 255) / 255, g: ((hex >> 8) & 255) / 255, b: (hex & 255) / 255 };
}

/** `Rgb` → 0xrrggbb (канали обрізано до 0–1). */
export function toHex(c: Rgb): number {
  const ch = (v: number): number => Math.round(Math.min(1, Math.max(0, v)) * 255);
  return (ch(c.r) << 16) | (ch(c.g) << 8) | ch(c.b);
}

export const WHITE: Rgb = { r: 1, g: 1, b: 1 };

/** Яскравість кольору (luma Rec. 601), 0–1. */
export function luma(c: Rgb): number {
  return 0.299 * c.r + 0.587 * c.g + 0.114 * c.b;
}

