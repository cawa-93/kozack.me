// Вкладка галереї арту (крок 16, GRAPHICS_PLAN.md: «Шов хвилі 1»): окрема сторінка `gallery.html` лише в режимі
// розробки й на прев'ю показує кадри, скелети й анімації. Шелл галереї (F2) знаходить вкладки сам —
// `import.meta.glob("./tabs/*.ts")`, — тож спільного реєстру немає: кожна вкладка — модуль `src/dev/gallery/tabs/<id>.ts`,
// який експортує `TAB: GalleryTab`, і за кожен модуль відповідає один пакет (кадри — F2, скелети — F4, компонувальник —
// F4, далі — інтегратор). Тут лише типи.

import type Phaser from "phaser";

/** Що шелл дає вкладці, коли її відкривають. */
export interface GalleryContext {
  /**
   * Сцена галереї. Атлас у ній уже завантажено, або його немає — тоді `addArt` (`src/view/art/atlas.ts`) показує
   * заглушки.
   */
  scene: Phaser.Scene;
  /** Шар для об'єктів вкладки: його показує камера галереї; шелл чистить його, коли вкладку закривають. */
  layer: Phaser.GameObjects.Layer;
  /** DOM-панель для елементів керування вкладки (перемикачі, списки); шелл її очищає, коли вкладку закривають. */
  panel: HTMLElement;
  /** Час для анімацій, мс: з повзунка часу шелла, а коли повзунок відпущено — живий час. */
  time(): number;
  /**
   * Підписатися на зміну розміру області перегляду (CSS px): `listener` кличеться одразу й після кожної зміни; повертає
   * відписку. Шелл, що розміру не змінює, може цього не давати.
   */
  onResize?(listener: (width: number, height: number) => void): () => void;
}

/** Відкрита вкладка. */
export interface GalleryView {
  /** Щокадру: `time` — те саме, що `GalleryContext.time()`, `delta` — мс від минулого кадру (0, коли час стоїть). */
  update?(time: number, delta: number): void;
  /** Вкладку закривають: прибрати все своє (об'єкти, слухачі, відписки). */
  destroy(): void;
}

/** Модуль вкладки `tabs/<id>.ts` експортує `TAB`. */
export interface GalleryTab {
  /** Id вкладки — назва її файлу без `.ts`. */
  id: string;
  /** Назва на вкладці, українською. */
  title: string;
  /** Порядок вкладок: менше — лівіше. */
  order: number;
  /** Відкрити вкладку. */
  mount(ctx: GalleryContext): GalleryView;
}

/** Модуль вкладки, як його бачить `import.meta.glob("./tabs/*.ts")`. */
export interface GalleryTabModule {
  TAB: GalleryTab;
}
