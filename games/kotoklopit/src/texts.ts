export const minutesText = (m: number): string => (m >= 60 ? `${Math.floor(m / 60)}\u00a0год${m % 60 ? `\u00a0${m % 60}\u00a0хв` : ""}` : `${m}\u00a0хв`);

/**
 * Рядки картки аварії (§8.5, `ACCIDENT_TEXTS`): скільки забрали документи й ремонт і о котрій персонаж удома — а коли їхні години
 * доходять до часу сну, решта дня до нього й ніч; числа — ті самі, що перемотає `rewindAccident`. Далі
 * кожна втрата: ремонт — скільки справді заплатили (грошей могло бути менше), переляканий — кожен кіт поїздки, у переносці й на руках;
 * травмований кіт; і де кожен кіт просидів ці години, хоч би що він утратив.
 */
export function accidentLines(state: GameState): string[] {
  const accident = accidentOf(state);
  const trip = state.trip;
  if (!accident || !trip) return [];
  const address = state.character.address;
  const home = accidentHome(state);
  const left = Math.round(accidentBedtime(state) - state.minute);
  const first =
    home !== null
      ? fill(ACCIDENT_TEXTS.day, address, { тривалість: minutesText(accident.minutes), час: atClock(home) })
      : left > 0
        ? fill(ACCIDENT_TEXTS.night, address, { тривалість: minutesText(left) })
        : ACCIDENT_TEXTS.late;
  const riders = (trip.riders ?? []).flatMap((r) => state.cats.filter((c) => c.id === r.cat).map((cat) => ({ cat, place: r.place })));
  const each = (text: string, cats: readonly { cat: { sex: Sex; name: string } }[]): string[] => cats.map(({ cat }) => fill(text, cat.sex, { кіт: cat.name }));
  const loss = (kind: Exclude<AccidentLoss, "cat">): string => {
    if (kind !== "repair") return ACCIDENT_TEXTS[kind];
    const paid = trip.repaired ?? 0;
    const shown = Math.floor(paid);
    if (paid >= accident.repair) return fill(ACCIDENT_TEXTS.repair, address, { сума: shown });
    return shown > 0 ? fill(ACCIDENT_TEXTS.repairAll, address, { сума: shown }) : ACCIDENT_TEXTS.repairNone;
  };
  const carrier = home !== null ? ACCIDENT_TEXTS.carrierDay : ACCIDENT_TEXTS.carrierNight;
  const hands = home !== null ? ACCIDENT_TEXTS.handsDay : ACCIDENT_TEXTS.handsNight;
  const injured = riders.filter((r) => trip.injured?.includes(r.cat.id) === true);
  const losses = trip.losses.flatMap((kind) => (kind === "cat" ? each(ACCIDENT_TEXTS.cat, riders) : [loss(kind)]));
  return [
    first,
    ...(losses.length + injured.length > 0 ? losses : [ACCIDENT_TEXTS.none]),
    ...each(ACCIDENT_TEXTS.injured, injured),
    ...each(carrier, riders.filter((r) => r.place !== "hands")),
    ...each(hands, riders.filter((r) => r.place === "hands")),
  ];
}

