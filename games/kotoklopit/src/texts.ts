/**
 * Варіант тексту для кота (рішення автора 2026-10-29, `GENERAL_REVIEW.md`, А18): обирає номер кота, а не випадковість, тож у того
 * самого кота текст той самий на прощанні, в альбомі й на переграванні, а кошенята одного виводку (номери поспіль) дістають різні.
 * `shift` 1 зсуває варіант на кожному наступному колі номерів: так варіанти причини й опису життя поєднуються по-різному, а не
 * завжди другий із другим.
 */
export function textVariant(text: string | readonly string[], id: number, shift: 0 | 1 = 0): string {
  if (typeof text === "string") return text;
  const n = text.length;
  const index = (id + shift * Math.floor(id / n)) % n;
  return text[(index + n) % n] ?? "";
}

