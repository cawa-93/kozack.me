// Імена котів для нових кошенят. Ім'я обирається з умов дня, тож на переграванні воно те саме (§6.1).

import type { Rng } from "./rng";
import type { Sex } from "./types";

// По 24 імені на стать (перевірка розмноження 2026-10-28: було по 12, і з десятком котів імена повторювалися).
export const CAT_NAMES: Record<Sex, readonly string[]> = {
  male: [
    "Барсик", "Мурчик", "Пушок", "Тигрик", "Рижик", "Вуглик", "Персик", "Коцько", "Боцман", "Сирник", "Пиріжок", "Філя",
    "Гарбузик", "Кекс", "Шустрик", "Мармелад", "Котигорошко", "Пухнастик", "Тимко", "Оладко", "Кузя", "Бегемотик", "Мурко", "Димок",
  ],
  female: [
    "Мурка", "Ласка", "Перлинка", "Зірка", "Маруся", "Дуся", "Ромашка", "Ожина", "Квасоля", "Пампушка", "Намистинка", "Хмаринка",
    "Мася", "Киця", "Пушинка", "Карамелька", "Ягідка", "Сніжинка", "Фіалка", "Ластівка", "Плюшка", "Шоколадка", "Ірися", "Муся",
  ],
};

/** Ім'я, якого ще немає серед `taken`; якщо всі зайняті — з номером («Мурка 2»), щоб двох котів не звали однаково. */
export function pickCatName(rng: Rng, sex: Sex, taken: readonly string[]): string {
  const names = CAT_NAMES[sex];
  const free = names.filter((name) => !taken.includes(name));
  if (free.length > 0) return free[rng.int(0, free.length - 1)] ?? names[0] ?? "Кіт";
  const base = names[rng.int(0, names.length - 1)] ?? "Кіт";
  let n = 2;
  while (taken.includes(`${base} ${n}`)) n += 1;
  return `${base} ${n}`;
}
