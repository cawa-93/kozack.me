import type { Cat, Trait, TraitLevel } from "./types";

export interface TraitGroup {
  id: string;
  /** Назва групи з довідника. */
  title: string;
  /** Добрий бік (§9.1): 1 — «+», −1 — «−». */
  good: 1 | -1;
  /** Назви рівнів +2, +1, −1, −2. */
  names: readonly [string, string, string, string];
  /** Тиха риса не проявляється в поведінці (§9.9). */
  quiet?: true;
  /** Нічна риса проявляється, коли персонаж спить, тож спостереженням її не відкрити (`TRAITS.md`). */
  nocturnal?: true;
}

