const BY_ID = new Map(TRAIT_GROUPS.map((g) => [g.id, g]));

export function traitGroup(id: string): TraitGroup {
  const found = BY_ID.get(id);
  if (!found) throw new Error(`Немає групи рис «${id}»`);
  return found;
}

/** Назва рівня риси у формі `[чоловіча|жіноча]`. */
export function traitName(trait: Pick<Trait, "group" | "level">): string {
  const names = traitGroup(trait.group).names;
  const index = { 2: 0, 1: 1, [-1]: 2, [-2]: 3 }[trait.level];
  return names[index] ?? "";
}

/** Риса позитивна, якщо вона на доброму боці групи (§9.1). */
export function isPositive(trait: Pick<Trait, "group" | "level">): boolean {
  return Math.sign(trait.level) === traitGroup(trait.group).good;
}

/** Рівень риси характеру в групі: 0 — риси немає. */
export function characterLevel(cat: Pick<Cat, "traits">, group: string): number {
  return cat.traits.find((t) => t.group === group)?.level ?? 0;
}

/** Рівень знаку `TraitLevel` для заданого знаку й сили. */
export function levelOf(sign: 1 | -1, strong: boolean): TraitLevel {
  return (sign * (strong ? 2 : 1)) as TraitLevel;
}
