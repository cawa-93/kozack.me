// Назви — у форматі `[чоловіча|жіноча]`, як тексти гри (`TEXTS.md`).

import type { Cat, Trait, TraitLevel } from "./types";

/** Розділ рис (`TRAITS.md`): бабл першого рівня знання каже лише його (§9.9, `TRAIT_AREAS` у `src/texts.ts`). */
export type TraitArea = "energy" | "attention" | "food" | "hygiene" | "mischief" | "play" | "courage" | "cats" | "health";

export interface TraitGroup {
  id: string;
  /** Назва групи з довідника. */
  title: string;
  /** Розділ довідника. */
  area: TraitArea;
  /** Добрий бік (§9.1): 1 — «+», −1 — «−». */
  good: 1 | -1;
  /** Назви рівнів +2, +1, −1, −2. */
  names: readonly [string, string, string, string];
  /** Тиха риса не проявляється в поведінці (§9.9). */
  quiet?: true;
  /**
   * Який бік видно в поведінці (§9.9): «+», «−». Невидимий бік — тиха половина: підказки немає, рису знають, лише якщо її показали під час вибору кота.
   * Що саме зараховується як прояв — `TRAITS.md`.
   */
  shows?: readonly [boolean, boolean];
}

const group = (
  id: string,
  title: string,
  good: 1 | -1,
  names: readonly [string, string, string, string],
  flags: { quiet?: true; shows?: readonly [boolean, boolean] } = {},
): Omit<TraitGroup, "area"> => ({ id, title, good, names, ...flags });

/** Групи одного розділу довідника. */
const section = (area: TraitArea, groups: readonly Omit<TraitGroup, "area">[]): TraitGroup[] => groups.map((g) => ({ ...g, area }));

