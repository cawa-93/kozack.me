  room?: string;
  /** Нявкання за роботою (§9.12, «Балакучість»): година гри й скільки здорового глузду воно за неї забрало. */
  meowNoise?: { hour: number; lost: number };
  /** Хвороби персонажа (§6.5). */
  illnesses: Illness[];
  /** Скільки ночей поспіль персонаж недоспав, і скільки — добре виспався (§6.5). */
  shortNights: number;
  restedNights: number;
