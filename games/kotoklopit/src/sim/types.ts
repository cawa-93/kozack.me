/** Комунальні цієї ночі (§6.4). */
export interface UtilitiesReport {
  /** billed — прийшов рахунок; evicted — новий прийшов, а старий ще не сплачено: виселення. */
  outcome: "billed" | "evicted";
  /** Новий рахунок, ₴; 0 — нараховувати нічого. */
  bill: number;
  /** У рахунку знижка «Перерахунку комунальних» (§4.1). */
  recalculated?: true;
}

/** Що сталося вночі: з цього будуються ранкові повідомлення (§4). */
export interface NightReport {
  /** День, що закінчився. */
  day: number;
  sleptHours: number;
  /** Персонаж не ліг сам, а впав без сил (§8.8). */
  collapsed: boolean;
  /** Ніч із неділі на понеділок. */
  weekly: boolean;
  /** Хто будив персонажа вночі (§8.8). */
  /** Чому будив: ранкова побудка, нічний неспокій, кахикання перед шерстяною грудкою (§9.12). */
  wakeUps: { cat: number; reason: "morning" | "night" | "hairball" }[];
  /** Хвилина нового дня, коли персонаж прокинувся. */
  wokeMinute: number;
  /** Розбудили «Галасливі сусіди» (§4.1): хвилина нового дня; немає — не вони. */
  neighborsWoke?: number;
  /** Кроки ночі в порядку виконання. */
  steps: NightStep[];
  lostCats: number[];
  /** Коти, яких забрали нові господарі (§9.8). */
  givenCats: number[];
  /** Оголошення, зняті вночі: кішка народила й годує кошенят. */
  keptCats?: number[];
  newCats: number[];
  utilities: UtilitiesReport | null;
  /** Гроші тижня, що закінчився (§6.4, «Куди йдуть гроші»): лише в ніч на понеділок. */
  ledger: Ledger | null;
  sanityEvening: number;
  sanityMorning: number;
  /** Сусідка забрала посилки зранку: персонаж ліг, не дочекавшись її (§4.1 «Сусідські посилки»). */
  parcels?: ParcelsPickup;
}

/** Сусідка забрала посилки (§4.1 «Сусідські посилки»): скільки їх було, скільки пошкоджених, компенсація й скільки з неї сплачено. */
export interface ParcelsPickup {
  count: number;
  damaged: number;
  fine: number;
  paid: number;
}

/**
 * На що пішли гроші (§6.4, «Куди йдуть гроші», рішення автора 2026-10-27): корм і запаси, речі, доставка, комунальні,
 * ветеринар і лікар, решта.
 */
export type Spending = "supplies" | "things" | "delivery" | "utilities" | "health" | "other";

/** Гроші за тиждень (§6.4): скільки заробили й скільки витратили на кожну категорію. */
export interface Ledger {
  earned: number;
  spent: Partial<Record<Spending, number>>;
}

/** Статистика гри (§4.2). */
export interface GameStats {
  /** Хвилини: робота (й пошук роботи), коти, собі, «метушня» — ходіння між справами. */
  minutes: { work: number; cats: number; self: number; bustle: number };
  /** Скільки котів виростив персонаж, за тим, звідки вони. */
  raised: Record<CatSource, number>;
}

/**
 * Хто дзвонить у двері й заходить сам (§9.12 «Двері й гості», «Час на реакцію»): мама з гостинцями, ветеринарка, представник
 * ОСББ, гості, прибиральниця, кур'єр із сусідськими посилками (`parcels`) і сусідка, що по них приходить (`neighbor`) (§4.1).
 * Кур'єр із покупками лише лишає пакунок — його тут немає.
 */
export type DoorGuest = "mom" | "home-vet" | "inspection" | "guests" | "cleaner" | "parcels" | "neighbor";

/** Що сьогодні відбувається за модифікатором (§4.1). */
export interface ModifierDay {
  /** Коли подзвонить мама; null — дзвінка немає чи вже був. */
  callAt: number | null;
  /**
   * Мама подзвонила, а гравець ще не вирішив, відповісти чи ні (§4.1): після перезавантаження картку дзвінка показують знову.
   * Немає — дзвінок не чекає.
   */
  callPending?: boolean;
  /** Хвилини за комп'ютером на важливій нараді. */
  meetingMinutes: number;
  /** Сьогодні вже були в офісі. */
  officeDone: boolean;
  /** «Гості» вже зайшли: до кінця дня — тригер міток (§9.12 «Мітки»). */
  guestsCame?: true;
  /** Персонаж ліг спати — велику коробку винесли на макулатуру (§4.1, `sim/bigbox.ts`). */
  bigBoxGone?: true;
  /** Сьогодні вже брали участь у виставці котів. */
  showDone?: boolean;
  /** Під дверима знайда, рішення ще не ухвалено. */
  foundling: boolean;
  /** Коли востаннє була знайда. */
  lastFoundling: number;
  /** Знижка на найближчі комунальні (перерахунок). */
  utilitiesDiscount: number;
  /** Хвилина пробудження цієї ночі раніше на стільки (галасливі сусіди). */
  earlyWake: number;
  /**
   * Візит мами з гостинцями (§4.1, рішення автора 2026-10-26): `at` — коли вона дзвонить у двері (хвилина дня); `rang` — уже
   * подзвонила й заходить за `GUESTS.ringLead` хвилин; `porch` — не застала персонажа й лишила гостинці під дверима. Немає —
   * мами сьогодні немає чи вона вже була.
   */
  mom?: { at: number; rang?: true; porch?: true };
  /**
   * День «Сусідські посилки» (§4.1): чий візит попереду — кур'єра з посилками (`courier`) чи сусідки (`neighbor`); `rang` — хвилина
   * дня, коли він подзвонив (заходить за `GUESTS.ringLead` хвилин). Немає — посилок сьогодні немає чи сусідка вже їх забрала.
   */
  parcels?: { stage: "courier" | "neighbor"; rang?: number };
  /**
   * Гість під дверима (§9.12 «Подзвонили — двері гостю», рішення автора 2026-11-03): `who` подзвонив і заходить сам у призначену
   * хвилину; `in` — гравець відчинив йому раніше, візит уже був, і в призначену хвилину він не повторюється. Запис знімає
   * призначена хвилина візиту чи ранок. Під дверима — щонайбільше один: усі вони — події дня (§4.1), а сусідка дзвонить лише після
   * кур'єра з посилками. Немає — під дверима ніхто не чекає.
   */
  guest?: { who: DoorGuest; in?: true };
}

export interface GameState {
  seed: number;
  /** Скільки разів гравець переграв день чи тиждень; змінює поведінку котів (§6.1). */
  replays: number;
  difficulty: Difficulty;
  /** День гри від 0; 0 — понеділок першого тижня. */
  day: number;
  /** Хвилина від 00:00 дати дня; після півночі більша за 1440, доки персонаж не ляже. */
  minute: number;
  /** Хвилина, з якої почався день: пробудження чи побудка котами (§8.8). */
  dayStartMinute: number;
  character: Character;
  /** Поїздка, якщо персонаж зараз поза домом (§8.5). */
  trip: Trip | null;
  /** Котів притулку й розплідника цього тижня (§8.5): вибір фіксований на тиждень. */
  shelter: { week: number; cats: Cat[] } | null;
  breeder: { week: number; breed: string; cats: Cat[] } | null;
  /** Коти, яких завтра заберуть за оголошенням (§9.8). */
  ads: number[];
  job: Job;
  home: Home;
  modifiers: { day: string | null; week: string | null };
  /** Статистика для екрана кінця гри (§4.2): хвилини за категоріями й виховані коти. */
  stats: GameStats;
  /** Стан модифікаторів дня (§4.1): дзвінок, нарада, офіс, знайда тощо. */
  today: ModifierDay;
  cats: Cat[];
  /** «Альбом пам'яті» (§9.7): коти, яких більше немає. */
  album: AlbumEntry[];
  /** Стосунки пар котів −100…+100 (§9.4): ключ — `id-id`, менший id першим. */
  relations: Record<string, number>;
  /**
   * Пари, що сьогодні сварилися за ресурс чи билися (§9.4 «Згода, охорона й сварки», рішення автора 2026-10-26, Б6): ключ — як у
   * `relations`. Уночі від цього залежить зближення, і список починається заново.
   */
  strife?: Record<string, { quarrel?: true; fight?: true }>;
  /** «Котячі розбірки» (§4.1): на скільки вже впали стосунки пар за день `day`; ключ — як у `relations`. */
  feudDrop?: { day: number; drop: Record<string, number> };
  /** Гроші цього тижня (§6.4, «Куди йдуть гроші»): у ніч на понеділок ідуть у звіт ночі й рахуються наново. */
  ledger?: Ledger;
  /** Наступний id для котів, речей, безладу й пакунків. */
  nextId: number;
  rng: Record<RngStream, number>;
  lastNight: NightReport | null;
  end: GameEnd | null;
}

/** Збереження: поточний стан і знімки для перегравання (§6.1). */
export interface Save {
  version: number;
  current: GameState;
  dayStart: GameState;
  weekStart: GameState;
  /**
   * Ранок поточного дня, якщо він настав після аварії й тому не став знімком перегравання (§6.1, §8.5; рішення автора
   * 2026-10-29, `GENERAL_REVIEW.md`, А1); `null` — ранок поточного дня і є `dayStart`. Наступна ніч після ще однієї аварії
   * зробить його знімком дня.
   */
  morning: GameState | null;
}
